// Перезагрузка лент главного экрана после изменений на сервере.
//
// HomeScreen живёт внутри IndexedStack в Shell: он не пересоздаётся, когда
// пользователь возвращается с экрана финиша заплыва, создания заплыва или
// публикации маршрута. Без явного вызова ленты (ближайшие заплывы,
// маршруты, «Ваша статистика», активность) оставались с прошлыми данными —
// отсюда ощущение «заплывы и маршруты не синхронизировались».
//
// Точки, которые меняют данные на сервере, обязаны вызывать refreshHomeFeeds.
import 'dart:async';

import 'feed_controller.dart';
import 'home_controller.dart';

/// Обновляет агрегаты главной и социальную ленту. Не ждём ответа — экрану
/// важнее остаться отзывчивым, секции сами покажут прогресс.
void refreshHomeFeeds(HomeController home, FeedController feed) {
  unawaited(home.refreshAll());
  unawaited(feed.refresh());
}
